/* Stars screensaver: dark night sky with CSS-only twinkling stars and a plain white clock. */
HGWall.xsDef('stars', hgTLazy('wallx.styles.stars'), false, {
  cls: 'st',
  css: `
.nx-st{ background:${K(2,4,14,1)}; overflow:hidden; }
.nx-st .nx-t{ font-size:clamp(84px, 22vmin, 260px); font-weight:200; letter-spacing:-.045em;
  color:${K(255,255,255,1)}; text-shadow:0 2px 32px ${K(0,0,0,.45)}, 0 0 80px ${K(255,255,255,.08)}; }
.nx-st .nx-dt{ color:${K(255,255,255,.82)}; text-shadow:0 1px 8px ${K(0,0,0,.5)}; }
.nx-st .nx-wx{ color:${K(255,255,255,.85)}; text-shadow:0 1px 6px ${K(0,0,0,.5)}; }
/* Star field: generated by body(), animated with CSS keyframes */
.nx-st-sky{ position:absolute; inset:0; pointer-events:none; overflow:hidden; }
.nx-st-star{ position:absolute; border-radius:50%; background:${K(255,255,255,1)};
  animation:var(--hg-loop, nx-st-twinkle var(--nx-st-dur, 3s) ease-in-out infinite alternate); }
@keyframes nx-st-twinkle{
  0%{ opacity:var(--nx-st-lo, .2); transform:scale(1); }
  100%{ opacity:var(--nx-st-hi, 1); transform:scale(var(--nx-st-sc, 1.4)); }
}
@media (prefers-reduced-motion:reduce){ .nx-st-star{ animation:none; opacity:.5; } }
`,
  body() {
    /* Generate ~200 stars pseudo-randomly (seeded loop, no Math.random for reproducibility). */
    let stars = '<div class="nx-st-sky" aria-hidden="true">';
    /* Simple LCG for deterministic star positions. */
    let seed = 0x9e3779b9;
    const rand = () => { seed = (seed ^ (seed << 13)) >>> 0; seed = (seed ^ (seed >>> 7)) >>> 0; seed = (seed ^ (seed << 17)) >>> 0; return (seed >>> 0) / 0xffffffff; };
    for (let i = 0; i < 220; i++) {
      const x = (rand() * 100).toFixed(2);
      const y = (rand() * 100).toFixed(2);
      const sz = (rand() * 2.2 + 0.6).toFixed(2);
      const lo = (rand() * 0.25 + 0.1).toFixed(2);
      const hi = (rand() * 0.55 + 0.45).toFixed(2);
      const dur = (rand() * 4 + 2).toFixed(2);
      const sc = (rand() * 0.5 + 1.1).toFixed(2);
      const delay = (rand() * -8).toFixed(2);
      stars += `<span class="nx-st-star" style="left:${x}%;top:${y}%;width:${sz}px;height:${sz}px;--nx-st-lo:${lo};--nx-st-hi:${hi};--nx-st-dur:${dur}s;--nx-st-sc:${sc};animation-delay:${delay}s"></span>`;
    }
    stars += '</div>';
    return `${stars}<div class="nx-in"><time class="nx-t"></time><p class="nx-dt"></p><div class="nx-wx" hidden></div></div>`;
  },
  draw(root, T, d, rm) {
    const t = root.querySelector('.nx-t');
    if (!t) return;
    const html = `${H.esc(T.t)}${T.ap ? `<small>${H.esc(T.ap)}</small>` : ''}`;
    if (t.dataset.k !== html) { t.dataset.k = html; t.innerHTML = html; }
  },
});
